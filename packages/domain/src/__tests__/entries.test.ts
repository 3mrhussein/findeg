describe('root runtime entry', () => {
  it('exposes exactly the pinned runtime names', () => {
    expect(Object.keys(root).sort()).toEqual([...ROOT_RUNTIME_EXPORTS].sort());
  });

  it('keeps every area subpath, each a subset of the root (contraction is #443)', async () => {
    const areas = [
      '@findeg/domain/common',
      '@findeg/domain/customers',
      '@findeg/domain/catalog',
      '@findeg/domain/partners',
      '@findeg/domain/school-lists',
      '@findeg/domain/orders',
      '@findeg/domain/inventory',
      '@findeg/domain/relations',
    ];
    const rootNames = new Set(Object.keys(root));
    for (const area of areas) {
      const names = Object.keys(await (import(area) as Promise<object>));
      expect(
        names.filter((name) => !rootNames.has(name)),
        area,
      ).toEqual([]);
    }
  });
});

describe('root types entry', () => {
  it('carries types only: importing it yields no runtime value', async () => {
    const runtime = await import('@findeg/domain/types');
    expect(Object.keys(runtime)).toEqual([]);
  });

  it('exposes the domain types the root index exports', () => {
    expectTypeOf<Customer>().toEqualTypeOf<root.Customer>();
    expectTypeOf<Money>().toEqualTypeOf<root.Money>();
    expectTypeOf<Order>().toEqualTypeOf<root.Order>();
    expectTypeOf<OrderId>().toEqualTypeOf<root.OrderId>();
    expectTypeOf<Relation>().toEqualTypeOf<root.Relation>();
    expectTypeOf<EntityName>().toEqualTypeOf<root.EntityName>();
  });
});
